-- =========================================================
-- C# + MySQL 학생관리 프로그램 데이터베이스 생성 스크립트
-- =========================================================
-- 실행 위치: MySQL Workbench
-- 실행 계정: 데이터베이스 및 사용자 생성 권한이 있는 root 등의 관리자 계정
-- =========================================================


-- ---------------------------------------------------------
-- 1. 데이터베이스 생성
-- ---------------------------------------------------------

-- student_db 데이터베이스가 존재하지 않을 때만 새로 생성합니다.
-- IF NOT EXISTS를 사용하므로 이미 데이터베이스가 있어도 오류가 발생하지 않습니다.
CREATE DATABASE IF NOT EXISTS student_db

    -- 한글과 이모지 등을 안전하게 저장할 수 있도록
    -- 문자 인코딩을 utf8mb4로 설정합니다.
    CHARACTER SET utf8mb4

    -- MySQL 8에서 제공하는 유니코드 정렬 규칙을 사용합니다.
    -- ai: 악센트를 구분하지 않음
    -- ci: 대소문자를 구분하지 않음
    COLLATE utf8mb4_0900_ai_ci;


-- ---------------------------------------------------------
-- 2. C# 프로그램에서 사용할 MySQL 사용자 생성
-- ---------------------------------------------------------

-- student_app이라는 MySQL 사용자를 생성합니다.
-- 'localhost'는 MySQL 서버가 설치된 같은 컴퓨터에서만
-- 이 계정으로 접속할 수 있다는 의미입니다.
--
-- IF NOT EXISTS를 사용하므로 계정이 이미 존재하면
-- 새로운 계정을 다시 만들지 않습니다.
CREATE USER IF NOT EXISTS 'student_app'@'localhost'

    -- student_app 계정의 비밀번호를 설정합니다.
    -- 실제 프로젝트에서는 change_me 대신 안전한 비밀번호를 사용해야 합니다.
    IDENTIFIED BY 'change_me';


-- ---------------------------------------------------------
-- 3. 애플리케이션 사용자에게 권한 부여
-- ---------------------------------------------------------

-- student_app 사용자에게 학생관리 프로그램 실행에 필요한
-- 최소한의 데이터 처리 권한만 부여합니다.
--
-- SELECT : 데이터 조회
-- INSERT : 데이터 등록
-- UPDATE : 데이터 수정
-- DELETE : 데이터 삭제
GRANT SELECT, INSERT, UPDATE, DELETE

    -- student_db.*는 student_db 데이터베이스에 포함된
    -- 모든 테이블을 의미합니다.
    ON student_db.*

    -- 권한을 받을 사용자 계정을 지정합니다.
    TO 'student_app'@'localhost';


-- ---------------------------------------------------------
-- 4. 작업할 데이터베이스 선택
-- ---------------------------------------------------------

-- 이후 실행되는 CREATE TABLE과 INSERT 명령이
-- student_db 데이터베이스를 대상으로 실행되도록 지정합니다.
USE student_db;


-- ---------------------------------------------------------
-- 5. 학생정보 테이블 생성
-- ---------------------------------------------------------

-- students 테이블이 존재하지 않을 때만 새로 생성합니다.
-- 이미 테이블이 존재하면 오류 없이 다음 명령으로 넘어갑니다.
CREATE TABLE IF NOT EXISTS students
(
    -- 학생 데이터의 내부 식별번호입니다.
    -- INT          : 정수 데이터 형식
    -- NOT NULL     : 반드시 값이 있어야 함
    -- AUTO_INCREMENT: 학생을 등록할 때 1씩 자동 증가
    id INT NOT NULL AUTO_INCREMENT,

    -- 학생의 학번을 저장합니다.
    -- 최대 20자까지 저장할 수 있으며 반드시 입력해야 합니다.
    student_number VARCHAR(20) NOT NULL,

    -- 학생 이름을 저장합니다.
    -- 최대 50자까지 저장할 수 있으며 반드시 입력해야 합니다.
    name VARCHAR(50) NOT NULL,

    -- 학생의 학과명을 저장합니다.
    -- 최대 100자까지 저장할 수 있으며 반드시 입력해야 합니다.
    department VARCHAR(100) NOT NULL,

    -- 학생의 연락처를 저장합니다.
    -- 최대 30자까지 저장할 수 있습니다.
    -- 연락처가 입력되지 않으면 빈 문자열이 기본값으로 저장됩니다.
    phone VARCHAR(30) NOT NULL DEFAULT '',

    -- 학생정보가 등록된 날짜와 시간을 저장합니다.
    -- 값을 직접 입력하지 않으면 현재 날짜와 시간이 자동으로 저장됩니다.
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- id 열을 students 테이블의 기본키로 설정합니다.
    -- 기본키는 각 학생 데이터를 고유하게 식별합니다.
    CONSTRAINT pk_students
        PRIMARY KEY (id),

    -- 동일한 학번이 두 번 등록되지 않도록
    -- student_number 열에 UNIQUE 제약조건을 설정합니다.
    CONSTRAINT uq_students_student_number
        UNIQUE (student_number)
);


-- ---------------------------------------------------------
-- 6. 실습용 학생 데이터 등록
-- ---------------------------------------------------------

-- students 테이블에 학생정보 3건을 등록합니다.
-- id와 created_at은 자동으로 생성되므로 INSERT 열에서 제외합니다.
INSERT INTO students
(
    student_number, -- 학번
    name,           -- 이름
    department,     -- 학과
    phone           -- 연락처
)
VALUES
    -- 첫 번째 학생정보
    ('2026001', '김민준', '컴퓨터공학과', '010-1234-5678'),

    -- 두 번째 학생정보
    ('2026002', '이서연', '전자공학과', '010-2345-6789'),

    -- 세 번째 학생정보
    ('2026003', '박지훈', '소프트웨어학과', '010-3456-7890')

-- 동일한 학번이 이미 존재할 경우 INSERT 오류를 발생시키지 않고
-- 기존 행의 student_number를 같은 값으로 다시 설정합니다.
-- 결과적으로 이 스크립트를 여러 번 실행해도
-- 동일한 학번의 학생 데이터가 중복 등록되지 않습니다.
ON DUPLICATE KEY UPDATE
    student_number = VALUES(student_number);


-- ---------------------------------------------------------
-- 7. 생성된 학생 데이터 확인
-- ---------------------------------------------------------

-- students 테이블에 저장된 모든 학생정보를 조회합니다.
-- 스크립트 실행 결과를 확인할 때 사용할 수 있습니다.
SELECT
    id,
    student_number,
    name,
    department,
    phone,
    created_at
FROM students
ORDER BY id;